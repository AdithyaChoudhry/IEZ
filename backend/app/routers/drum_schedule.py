"""
Drum Schedule Generator (a sub-module of the Cable Schedule Generator).

IODB (the same bytes the Cable Schedule uses) + Drum Master Excel -> sequential drum allocation.
Stateless apart from a per-user "last generated workbook" cache for the download.

/generated/* - the page's input: the Cable Schedule last generated by the user for the project (+ the Drum Master).
The generated schedule decides WHICH cables are scheduled (its junction box selection included). Each cable's type,
length and IS/NIS are read, exactly as before, from the IODB that schedule was generated from: the schedule sheets
have no IS/NIS column and the drum allocation matches cable type + IS/NIS, so nothing is guessed. The allocation
itself (utils.drum_schedule) is unchanged.
"""
import io
from typing import Optional

from utils.xlsx_trim import trim_empty_tail
from fastapi import APIRouter, Depends, File, Form, HTTPException, UploadFile, status
from fastapi.responses import StreamingResponse

from ..auth.models import User
from ..deps import get_current_user
from .cable_schedule import require_generated

import sys
sys.path.insert(0, '/app')
from utils import drum_schedule as ds  # noqa: E402
from utils.cable_schedule_extra import ExtraSheetError  # noqa: E402

router = APIRouter(prefix="/cable-schedule/drum", tags=["Drum Schedule"])
drum_cache: dict = {}
MAX_BYTES = 25 * 1024 * 1024


def _bad(msg: str, code: int = status.HTTP_400_BAD_REQUEST):
    raise HTTPException(status_code=code, detail=msg)


async def _read(upload: UploadFile, what: str) -> bytes:
    data = trim_empty_tail(await upload.read())
    if not data:
        _bad(f"The {what} file is empty.")
    if len(data) > MAX_BYTES:
        _bad(f"The {what} file is larger than 25 MB.")
    if not (upload.filename or "").lower().endswith((".xlsx", ".xlsm")):
        _bad(f"The {what} must be an Excel .xlsx file.")
    return data


def _iodb_frame(data: bytes):
    from utils.file_handler import read_iodb
    df, err = read_iodb(io.BytesIO(data))
    if err:
        _bad(f"Failed to read IODB: {err}")
    return df


def _issues(issues, limit=40):
    return [dict(severity=i.severity, kind=i.kind, ref=i.ref, message=i.message)
            for i in sorted(issues, key=lambda i: {"ERROR": 0, "WARNING": 1, "INFO": 2}[i.severity])][:limit]


@router.post("/demand")
async def drum_demand(iodb_file: UploadFile = File(...), current_user: User = Depends(get_current_user)):
    """Step 1: how many cable requirements the IODB gives (branch + main, shared main cables once) and its problems."""
    df = _iodb_frame(await _read(iodb_file, "IODB"))
    try:
        demands, issues, stats = ds.extract_demand(df)
    except (ds.DrumError, ExtraSheetError) as e:
        _bad(str(e))
    return _demand_payload(demands, issues, stats)


def _demand_payload(demands, issues, stats) -> dict:
    counts: dict = {}
    for i in issues:
        counts[i.severity] = counts.get(i.severity, 0) + 1
    types = {}
    for d in demands:
        k = (d.cable_type, d.is_nis or "-")
        types[k] = types.get(k, 0) + d.length
    return {"stats": stats, "issues": _issues(issues), "issue_counts": counts,
            "cable_types": [dict(cable_type=k[0], is_nis=k[1], required=ds.fmt(v)) for k, v in sorted(types.items())]}


def _schedule_texts(xlsx: bytes) -> set:
    """Every text value of the generated workbook's schedule sheets (the cable tags are among them)."""
    import openpyxl
    from utils.cable_summary import CABLE_SUMMARY_SHEET
    wb = openpyxl.load_workbook(io.BytesIO(xlsx), read_only=True)
    try:
        return {v.strip().upper() for ws in wb.worksheets if ws.title.strip().upper() != CABLE_SUMMARY_SHEET.strip().upper()
                for row in ws.iter_rows(values_only=True) for v in row if isinstance(v, str) and v.strip()}
    finally:
        wb.close()


def _generated_demand(g: dict):
    """ds.extract_demand on the IODB the generated schedule came from, limited to the cables that schedule contains."""
    df = _iodb_frame(g["iodb_bytes"])
    try:
        demands, issues, stats = ds.extract_demand(df)
    except (ds.DrumError, ExtraSheetError) as e:
        _bad(str(e))
    in_schedule = _schedule_texts(g["bytes"])
    kept = [d for d in demands if d.tag.strip().upper() in in_schedule]
    left = [d for d in demands if d.tag.strip().upper() not in in_schedule]
    if demands and not kept:
        _bad(f"None of the {len(demands)} cables of the IODB appear in the generated Cable Schedule {g['filename']}. "
             "Generate the Cable Schedule again.")
    if left:
        tags = ", ".join(d.tag for d in left[:8]) + (f" +{len(left) - 8} more" if len(left) > 8 else "")
        issues.append(ds.Issue("INFO", "SCHEDULE", "Not in the generated Cable Schedule", f"{len(left)} cable(s)",
                               f"Not scheduled - they are not in {g['filename']} (e.g. a junction box that was not selected): {tags}."))
    stats = dict(stats)
    stats.update({"demand": len(kept), "branch": sum(1 for d in kept if d.category == "BRANCH"),
                  "main": sum(1 for d in kept if d.category == "MAIN"), "total_length": ds.fmt(sum(d.length for d in kept)),
                  "not_in_schedule": len(left)})
    return kept, issues, stats


def _generated_source(g: dict) -> dict:
    return {"type": "GENERATED", "name": g["filename"], "id": g["id"], "generated_at": g["generated_at"],
            "iodb_filename": g["iodb_filename"]}


@router.post("/generated/demand")
async def generated_demand(
    project_id: Optional[str] = Form(None),
    generated_id: Optional[str] = Form(None),
    current_user: User = Depends(get_current_user),
):
    """Step 1 with the generated Cable Schedule: the cable requirements it contains."""
    g = require_generated(current_user.id, project_id, generated_id)
    out = _demand_payload(*_generated_demand(g))
    out["source"] = _generated_source(g)
    return out


@router.post("/generated/generate")
async def generated_generate(
    drum_master_file: UploadFile = File(...),
    project_id: Optional[str] = Form(None),
    generated_id: Optional[str] = Form(None),
    min_residual: float = Form(ds.DEFAULT_MIN_RESIDUAL),
    use_master_split: bool = Form(True),
    current_user: User = Depends(get_current_user),
):
    """/generate with the generated Cable Schedule as the cable input (same steps as ds.run)."""
    g = require_generated(current_user.id, project_id, generated_id)
    master = await _read(drum_master_file, "Drum Master")
    try:
        min_residual = ds.check_settings(min_residual)
        demands, d_issues, d_stats = _generated_demand(g)
        lots, m_issues, m_info = ds.read_drum_master(master)
        res = ds.build_schedule(demands, lots, d_issues + m_issues, min_residual, use_master_split, {"demand": d_stats, "master": m_info})
        xlsx = ds.to_workbook(res)
    except (ds.DrumError, ExtraSheetError) as e:
        _bad(str(e))
    drum_cache[f"{current_user.id}_drum"] = {"bytes": xlsx, "filename": "Drum_Schedule.xlsx"}
    out = ds.payload(res)
    out["filename"] = "Drum_Schedule.xlsx"
    out["source"] = _generated_source(g)
    return out


@router.post("/master")
async def drum_master(drum_master_file: UploadFile = File(...), current_user: User = Depends(get_current_user)):
    """Step 2: read and validate the Drum Master."""
    data = await _read(drum_master_file, "Drum Master")
    try:
        lots, issues, info = ds.read_drum_master(data)
    except ds.DrumError as e:
        _bad(str(e))
