class LibraryError(Exception):
    """User-facing template library problem."""


# ── library ───────────────────────────────────────────────────────────────────
def _lib_path() -> Path:
    return LIB_DIR / "library.json"


@lru_cache(maxsize=4)
def _load(mtime: float) -> dict:
    data = json.loads(_lib_path().read_text())
    ids = [t["id"] for t in data["templates"]]
    if len(ids) != len(set(ids)):
        raise LibraryError("The template library has duplicate template ids.")
    return data


def library() -> list[dict]:
    p = _lib_path()
    if not p.exists():
        raise LibraryError("The datasheet template library is missing on the server.")
    return [t for t in _load(p.stat().st_mtime)["templates"] if t.get("active", True)]


def entry(template_id: str) -> dict:
    if not re.fullmatch(r"[a-z0-9_]{1,40}", template_id or ""):
        raise LibraryError("Unknown datasheet template.")
    for t in library():
        if t["id"] == template_id:
            f = LIB_DIR / t["file"]
            if not f.exists() or f.resolve().parent != LIB_DIR.resolve():
                raise LibraryError(f"The template file for '{t['display_name']}' is missing on the server.")
            return t
    raise LibraryError(f"Unknown or inactive datasheet template '{template_id}'.")


def template_bytes(t: dict) -> bytes:
    return (LIB_DIR / t["file"]).read_bytes()


@lru_cache(maxsize=16)
def _sheets_cached(template_id: str, mtime: float) -> dict[str, SheetModel]:
    t = entry(template_id)
    return read_workbook(template_bytes(t), t["file"])


def sheets_of(t: dict) -> dict[str, SheetModel]:
    return _sheets_cached(t["id"], (LIB_DIR / t["file"]).stat().st_mtime)


# ── sheet roles ───────────────────────────────────────────────────────────────
def _text(sm: SheetModel, rows: int = 12, cols: int = 14) -> str:
    return " ".join(sm.value(r, c) for r in range(min(rows, sm.nrows)) for c in range(min(cols, sm.ncols))).upper()


def classify_sheets(sheets: dict[str, SheetModel]) -> dict[str, Optional[str]]:
    """Role -> sheet name, from sheet names and content (not names alone)."""
    roles: dict[str, Optional[str]] = {r: None for r in ROLE_LABELS}
    for name, sm in sheets.items():
        n, head = name.strip().upper(), _text(sm)
        if "CHECKLIST" in n or head.lstrip().startswith("CHECKLIST"):
            roles["checklist"] = roles["checklist"] or name
        elif "COVER" in n:
            roles["cover"] = roles["cover"] or name
        elif n == "INDEX" or head.lstrip().startswith("INDEX"):
            roles["index"] = roles["index"] or name
        elif "SPARE" in n or "ANNEXURE - II" in head or "ANNEXURE-II" in head.replace(" ", ""):
            roles["annexure2"] = roles["annexure2"] or name
        elif "ANNEX" in n or "ANNEXURE - I" in head:
            if SC.parse_annexure(sm) is not None:
                roles["annexure"] = roles["annexure"] or name
        elif re.search(r"(^|[-_\s])(EG|EXAMPLE)\s*$", n) or "SOURCE" in " ".join(sm.value(r, 11).upper() for r in range(min(4, sm.nrows))):
            roles["example"] = roles["example"] or name
        elif "DATASHEET" in head or "DATA SHEET" in head:
            roles["main"] = roles["main"] or name
    return roles


def roles_for(t: dict) -> dict[str, Optional[str]]:
    sheets = sheets_of(t)
    detected = classify_sheets(sheets)
    pinned = t.get("sheets") or {}
    roles = {r: (pinned.get(r) if pinned.get(r) in sheets else detected[r]) for r in ROLE_LABELS}
    if not roles["main"] or roles["main"] not in sheets:
        raise LibraryError(f"The main datasheet sheet of '{t['display_name']}' could not be identified.")
    return roles


