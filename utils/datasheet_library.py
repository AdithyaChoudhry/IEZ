def _write_derived_annexure(wb, main_ws, lc: LibContext, recs: list[dict[int, Any]]) -> None:
    from openpyxl.styles import Alignment, Border, Font, Side
    from openpyxl.utils import get_column_letter
    ann = lc.ctx.annexure
    ws = wb.create_sheet(ann.sheet, index=wb.sheetnames.index(main_ws.title) + 1)
    thin = Side(style="thin")
    box = Border(left=thin, right=thin, top=thin, bottom=thin)
    font = main_ws.cell(9, 2).font
    fname = font.name if font and font.name else "Arial"
    ncols = len(ann.columns)
    last = get_column_letter(ncols)
    title = next((str(main_ws.cell(r, c).value) for r in range(1, 4) for c in range(1, 12)
                  if main_ws.cell(r, c).value and "DATASHEET" in str(main_ws.cell(r, c).value).upper()), lc.t["display_name"])
    ws.merge_cells(f"A1:{last}1")
    ws["A1"] = title
    ws.merge_cells(f"A2:{last}2")
    ws["A2"] = "ANNEXURE - I"
    for a in ("A1", "A2"):
        ws[a].font = Font(name=fname, bold=True, size=11)
        ws[a].alignment = Alignment(horizontal="center", vertical="center")
    for i, (lab, key) in enumerate((("CLIENT", "client"), ("PROJECT", "project"), ("PLANT", "plant"))):
        ws.cell(3 + i, 1, lab).font = Font(name=fname, bold=True, size=9)
        ws.cell(3 + i, 3, "XXXXXX").font = Font(name=fname, size=9)
    hr = ann.header_top + 1                                      # 1-based header row (7) and sub-header row (8)
    groups: dict[str, list] = {}
    for ac in ann.columns:
        groups.setdefault(ac.header, []).append(ac)
    for head, acs in groups.items():
        c1, c2 = acs[0].col + 1, acs[-1].col + 1
        if acs[0].sub:
            ws.merge_cells(start_row=hr, start_column=c1, end_row=hr, end_column=c2)
            for ac in acs:
                ws.cell(hr + 1, ac.col + 1, ac.sub)
        else:
            ws.merge_cells(start_row=hr, start_column=c1, end_row=hr + 1, end_column=c1)
        ws.cell(hr, c1, head)
    for r in (hr, hr + 1):
        for c in range(1, ncols + 1):
            cl = ws.cell(r, c)
            cl.font = Font(name=fname, bold=True, size=8)
            cl.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cl.border = box
    for i, rec in enumerate(recs):
        for ac in ann.columns:
            cl = ws.cell(ann.data_start + 1 + i, ac.col + 1, rec.get(ac.col))
            cl.font = Font(name=fname, size=8)
            cl.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cl.border = box
    for ac in ann.columns:
        ws.column_dimensions[get_column_letter(ac.col + 1)].width = 7 if ac.kind == "serial" else (16 if ac.kind == "tag" else 13)
    ws.row_dimensions[hr].height = 42
    SC._print_setup(ws, ann, max(len(recs), 1), ncols, keep_existing=False)
    ws.sheet_view.showGridLines = False


def resolve_main(lc: LibContext, overrides: dict, n_tags: int) -> dict[tuple[int, int], str]:
    out = {}
    for lf in lc.lib_fields:
        f = lf.spec
        ov = override_for(f, overrides)
        for idx, col in enumerate(f.value_cols):
            default = f.defaults[idx] if idx < len(f.defaults) else ""
            if lf.scope in ("tag", "annexure2"):
                val = default
            else:
                val = ov[idx] if (ov and idx < len(ov) and str(ov[idx]).strip() != "") else default
                if lf.origin == "computed" and not val and idx == 0:
                    val = f"{n_tags} NOS"
            out[(f.row, col)] = val
    return out


def output_filename(t: dict) -> str:
    code = re.sub(r"[^A-Za-z0-9]+", "_", t.get("code") or t["id"]).strip("_").upper()
    return f"{code}_CONSOLIDATED_DATASHEET.xlsx"


_SKIP_ASK = re.compile(r"remark", re.I)


def apply_annexure_values(ann: SC.AnnexureSpec, tags: list[str], recs: list[dict[int, Any]],
                          values: Optional[dict]) -> int:
    """Fill annexure cells the IODB left blank with the values the engineer typed ({tag: {column: value}}).
    An IODB value is never replaced. -> number of cells filled."""
    n = 0
    data_cols = {ac.col for ac in ann.columns if ac.kind == "data"}
    for tag, rec in zip(tags, recs):
        for col, v in ((values or {}).get(tag) or {}).items():
            try:
                c = int(col)
            except (TypeError, ValueError):
                continue
            v = str(v if v is not None else "").strip()
            if c in data_cols and v and rec.get(c) is None:
                rec[c] = v
                n += 1
    return n


def annexure_gaps(ann: SC.AnnexureSpec, tags: list[str], recs: list[dict[int, Any]]) -> list[dict]:
    """Annexure cells still blank (remarks excepted): what the engineer is asked to enter."""
    out = []
    for tag, rec in zip(tags, recs):
        for ac in ann.columns:
            if ac.kind == "data" and not _SKIP_ASK.search(ac.label) and rec.get(ac.col) is None:
                out.append({"tag": tag, "col": ac.col, "label": ac.label})
    return out


def generate(template_id: str, iodb_bytes: bytes, tags: list[str], overrides: Optional[dict] = None,
             user_mapping: Optional[dict] = None, header: Optional[dict] = None, field_scope: Optional[dict] = None,
             annexure_values: Optional[dict] = None) -> tuple[Optional[bytes], str, Optional[str], list[dict]]:
    """One consolidated workbook from a copy of the library template. -> (bytes, filename, error, failed)."""
    from openpyxl import load_workbook
    from openpyxl.cell.cell import MergedCell
    from .workbook_assembly import restore_template_fidelity
    overrides = overrides or {}
    try:
        lc = load_context(template_id, iodb_bytes, field_scope)
    except LibraryError as exc:
        return None, "", str(exc), []
    t, ctx = lc.t, lc.ctx
    filename = output_filename(t)
    clean_tags, _ = SC._unique(tags)
    rows, missing, _ = SC._rows_for(ctx, clean_tags)
    failed = [{"tag": x, "reason": "Tag not found in the IODB"} for x in missing]
    present = [x for x in clean_tags if x in rows]
    if not present:
        return None, filename, "No datasheet generated - none of the selected tags is in the IODB.", failed
    mapping = SC.normalize_mapping(ctx.annexure, [str(c) for c in ctx.df.columns], user_mapping)
    recs = SC.annexure_records(ctx, present, mapping, rows)
    apply_annexure_values(ctx.annexure, present, recs, annexure_values)
    src = template_bytes(t)
    wb = load_workbook(io.BytesIO(src))                           # an in-memory copy - the library file is only read
    keep = [lc.roles[r] for r in OUTPUT_ROLES if lc.roles.get(r)]
    for sn in list(wb.sheetnames):
        if sn not in keep:
            del wb[sn]
    ws = wb[lc.roles["main"]]
    for (r, c), value in resolve_main(lc, overrides, len(present)).items():
        cell = ws.cell(row=r + 1, column=c + 1)
        if not isinstance(cell, MergedCell):
            cell.value = value if value != "" else None
    first_row = min((lf.spec.row for lf in lc.lib_fields), default=8) + 1
    hdr = header or {}
    for name in keep:
        if name != lc.roles["annexure"] or lc.derived_annexure:
            fill_header(wb[name], hdr, first_row if name == lc.roles["main"] else None)
    if lc.derived_annexure:
        _write_derived_annexure(wb, ws, lc, recs)
        fill_header(wb[ctx.annexure.sheet], hdr)
    else:
        SC._expand_annexure_inplace(wb[lc.roles["annexure"]], ctx.annexure, recs)
        fill_header(wb[lc.roles["annexure"]], hdr)
    for w in wb.worksheets:
        w.sheet_state = "visible"
        w.sheet_view.tabSelected = w.title == ws.title
    wb.active = wb.sheetnames.index(ws.title)
    wb.calculation.fullCalcOnLoad = True                         # header cells are formulas reading the cover sheet
    buf = io.BytesIO()
    wb.save(buf)
    out = restore_template_fidelity(buf.getvalue(), src, [n for n in keep])
    return out, filename, None, failed


# ── library-specific validation (added to sop_consolidated.validate) ─────────────────────────────────────────────
def validate(template_id: str, iodb_bytes: bytes, tags: list[str], overrides: dict, user_mapping: Optional[dict],
             instrument_type: str = "", header: Optional[dict] = None, field_scope: Optional[dict] = None,
             ai_confidence: Optional[dict] = None, annexure_values: Optional[dict] = None) -> dict:
    lc = load_context(template_id, iodb_bytes, field_scope)
    res = SC.validate(lc.ctx, SC.CONSOLIDATED, tags, overrides, user_mapping)
    issues = res["issues"]

    def add(sev, code, msg, **kw):
        issues.append({"severity": sev, "code": code, "message": msg, **kw})

    # Annexure data the IODB does not give is asked from the engineer: the blank cells are listed, typed values fill them.
    if res.get("annexure") is not None:
        a = lc.ctx.annexure
        amap = SC.normalize_mapping(a, [str(c) for c in lc.ctx.df.columns], user_mapping)
        arows, _, _ = SC._rows_for(lc.ctx, SC._unique(tags)[0])
        present = [x for x in SC._unique(tags)[0] if x in arows]
        recs = SC.annexure_records(lc.ctx, present, amap, arows)
        filled = apply_annexure_values(a, present, recs, annexure_values)
        gaps = annexure_gaps(a, present, recs)
        issues[:] = [i for i in issues if i["code"] not in ("MISSING_TAG_DATA", "UNMAPPED_COLUMN")]
        by_col: dict[str, list[str]] = {}
        for g in gaps:
            by_col.setdefault(g["label"], []).append(g["tag"])
        for lab, ts in by_col.items():
            add("REVIEW", "MISSING_TAG_DATA", f"'{lab}' is not in the IODB for {len(ts)} tag(s): {', '.join(ts[:8])}"
                f"{' …' if len(ts) > 8 else ''} - enter it in the annexure table below or leave it blank on purpose.", field=lab)
        res["annexure"].update(preview=[{str(k): v for k, v in r.items()} for r in recs[:10]], missing=gaps[:3000],
                               missing_total=len(gaps), manual_filled=filled)

    t = lc.t
    if instrument_type:
        m = match_type(instrument_type)
        if m["template_id"] != t["id"]:
            add("REVIEW", "TEMPLATE_CHOSEN_MANUALLY",
                f"'{instrument_type}' was assigned to the '{t['display_name']}' template by hand"
                + (f" (iEZ matched '{m['template_id']}')." if m["template_id"] else " (iEZ found no match)."))
        elif m["status"] not in ("exact", "alias"):
            add("REVIEW", "UNCERTAIN_CLASSIFICATION",
                f"'{instrument_type}' was matched to '{t['display_name']}' by key words - confirm it is the right datasheet.")
    # duplicate IODB rows that disagree on annexure data
    ann = lc.ctx.annexure
    mapping = SC.normalize_mapping(ann, [str(c) for c in lc.ctx.df.columns], user_mapping)
    keyed = lc.ctx.df[lc.ctx.tag_col].astype(str).str.strip()
    for tag in SC._unique(tags)[0]:
        m_rows = lc.ctx.df[keyed == tag]
        if len(m_rows) > 1:
            diff = [ac.label for ac in ann.columns if ac.kind == "data" and mapping.get(ac.col)
                    and len({SC._cell(v) for v in m_rows[mapping[ac.col]].tolist()} - {None}) > 1]
            if diff:
                add("REVIEW", "CONFLICTING_TAG_DATA", f"Tag {tag}: its IODB rows disagree on {', '.join(diff[:4])} - the first row is used.", tag=tag)
    vendor = [lf.spec.label for lf in lc.lib_fields if lf.origin == "vendor" and not any(str(x).strip() for x in (override_for(lf.spec, overrides) or []))]
    if vendor:
        add("INFO", "VENDOR_DATA_PENDING", f"Vendor fields left blank until a vendor is selected: {', '.join(vendor)}.")
    for lf in lc.lib_fields:
        if lf.origin == "optional":
            add("REVIEW", "OPTIONAL_FIELD", f"'{lf.spec.label}' ({lf.spec.section}) is marked 'to be removed if not asked in the tender' - "
                                            "confirm the tender asks for it or clear its value.", field=lf.spec.label)
    if lc.roles.get("annexure2"):
        add("INFO", "ANNEXURE_II_TEMPLATE", "Annexure-II (mandatory spares) is kept as in the template - the spare percentage comes "
                                             "from the project specification and is not filled by iEZ.")
    if lc.derived_annexure:
        add("INFO", "ANNEXURE_GENERATED", f"The '{t['display_name']}' template has no annexure; iEZ builds Annexure-I from the "
                                           f"datasheet's tag-wise rows ({sum(1 for c in ann.columns if c.kind == 'data')} columns).")
    missing_hdr = [HEADER_FIELDS[k] for k in HEADER_FIELDS if not str((header or {}).get(k, "") or "").strip()]
    if missing_hdr:
        add("REVIEW", "HEADER_PLACEHOLDERS", f"Document header fields left as 'XXXXXX': {', '.join(missing_hdr)}.")
    for k, conf in (ai_confidence or {}).items():
        try:
            c = float(conf)
        except (TypeError, ValueError):
            continue
        if c < 0.6:
            add("REVIEW", "LOW_CONFIDENCE_AI", f"'{k.split('::')[-1]}' was extracted by AI with low confidence ({c:.0%}) - check it.", field=k)
    for n in lc.notes:
        add("REVIEW", "TEMPLATE_STRUCTURE", n)
    c = {"ERROR": 0, "REVIEW": 0, "INFO": 0}
    for i in issues:
        c[i["severity"]] = c.get(i["severity"], 0) + 1
    res["counts"] = c
    res["template"] = template_info(t, lc)
    return res


def template_info(t: dict, lc: Optional[LibContext] = None) -> dict:
    roles = roles_for(t)
    sheets = sheets_of(t)
    title = ""
    main = sheets[roles["main"]]
    for r in range(min(4, main.nrows)):
        for c in range(main.ncols):
            v = main.value(r, c).strip()
            if "DATASHEET" in v.upper():
                title = re.sub(r"\s+", " ", v)
                break
        if title:
            break
    ann = SC.parse_annexure(sheets[roles["annexure"]]) if roles["annexure"] else None
    lf = lc.lib_fields if lc else fields_for(t)[0]
    return {"id": t["id"], "code": t.get("code"), "display_name": t["display_name"], "category": t.get("category"),
            "version": t.get("version"), "original_filename": t.get("original_filename"), "title": title,
            "sheets": [{"role": r, "label": ROLE_LABELS[r], "sheet": roles[r], "in_output": r in OUTPUT_ROLES} for r in ROLE_LABELS if roles[r]],
            "all_sheets": list(sheets),
            "annexure": ({"sheet": roles["annexure"], "columns": len(ann.columns), "capacity": ann.capacity, "generated": False}
                         if ann else {"sheet": "ANNEXURE-I", "columns": len(_derived_annexure(t, main, lf).columns), "capacity": 0, "generated": True}),
            "field_counts": {"total": len(lf), "tag": sum(1 for x in lf if x.scope == "tag"),
                             "common": sum(1 for x in lf if x.scope == "common"), "vendor": sum(1 for x in lf if x.origin == "vendor")},
            "has_guide": bool(roles["example"]), "output_filename": output_filename(t)}
