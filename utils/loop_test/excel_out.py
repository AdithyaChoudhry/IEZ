"""
Excel output: one worksheet per loop, drawn from the same diagram model as the SVG preview.

White background, black rectangular equipment blocks, MISSING data in red, title block with
traceability, wiring schedule / signals / source tables. Orientation (vertical / horizontal)
follows the loop configuration.
"""
from __future__ import annotations

import io
import re
from datetime import datetime
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

THIN = Side(style="thin", color="000000")
MED = Side(style="medium", color="000000")
F_BASE = Font(name="Arial", size=10)
F_BOLD = Font(name="Arial", size=10, bold=True)
F_HEAD = Font(name="Arial", size=14, bold=True)
F_SMALL = Font(name="Arial", size=8, color="555555")
F_MISS = Font(name="Arial", size=10, italic=True, color="C00000")
FILL_HEAD = PatternFill("solid", fgColor="E6E6E6")
LEFT = Alignment(horizontal="left", vertical="center", wrap_text=True)
LEFT_NW = Alignment(horizontal="left", vertical="center", wrap_text=False)
FIT = Alignment(horizontal="left", vertical="center", shrink_to_fit=True)
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)


def safe_sheet_name(tag: str, used: set[str]) -> str:
    base = re.sub(r"[\[\]:*?/\\]", "-", tag).strip()[:31] or "LOOP"
    name, n = base, 2
    while name.lower() in used:
        suffix = f"~{n}"
        name, n = base[: 31 - len(suffix)] + suffix, n + 1
    used.add(name.lower())
    return name


def _box(ws, r0: int, c0: int, r1: int, c1: int) -> None:
    for r in range(r0, r1 + 1):
        for c in range(c0, c1 + 1):
            ws.cell(r, c).border = Border(left=MED if c == c0 else None, right=MED if c == c1 else None,
                                          top=MED if r == r0 else None, bottom=MED if r == r1 else None)


def _write_block(ws, b: dict, r0: int, c0: int, c1: int) -> int:
    """Draw one equipment block; returns the last row used."""
    rows = [("heading", b["heading"].upper()), ("title", b["title"] or "—")]
    rows += [("line", ln) for ln in b["lines"]]
    if b["terminals"]:
        rows.append(("terms", "   ".join(f'{t["label"]}:{t["value"]}' for t in b["terminals"])))
    r = r0
    for kind, content in rows:
        if c1 > c0:
            ws.merge_cells(start_row=r, start_column=c0, end_row=r, end_column=c1)
        cell = ws.cell(r, c0)
        cell.alignment = FIT
        if kind == "heading":
            cell.value, cell.font = content, F_SMALL
        elif kind == "title":
            cell.value, cell.font = content, F_BOLD
        elif kind == "line":
            cell.value, cell.font = content["text"], (F_MISS if content["missing"] else F_BASE)
        else:
            cell.value, cell.font = "▸ " + content, Font(name="Consolas", size=9)
        r += 1
    _box(ws, r0, c0, r - 1, c1)
    return r - 1


def _table(ws, r0: int, c0: int, title: str, headers: list[str], rows: list[list[Any]]) -> int:
    ws.cell(r0, c0, title).font = F_BOLD
    r = r0 + 1
    for j, h in enumerate(headers):
        c = ws.cell(r, c0 + j, h)
        c.font, c.fill, c.alignment = F_BOLD, FILL_HEAD, CENTER
        c.border = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
    for row in rows:
        r += 1
        for j, v in enumerate(row):
            c = ws.cell(r, c0 + j, v)
            c.font = F_MISS if v in ("MISSING", "NOT LINKED") else F_BASE
            c.alignment, c.border = LEFT_NW, Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
    return r + 2


def write_loop_sheet(ws, model: dict) -> None:
    vertical = model["orientation"] != "horizontal"
    main = [b for b in model["blocks"] if b["placement"] == "main"]
    side = [b for b in model["blocks"] if b["placement"] == "side"]
    ws.sheet_view.showGridLines = False
    tb = model["title_block"]

    ws["A1"].value = f"LOOP WIRING (TEST) — {model['tag']}"
    ws["A1"].font = F_HEAD
    info = [("Project", tb.get("project", "")), ("Tag", model["tag"]), ("Loop number", model["loop"] or "—"),
            ("Loop type", model["loop_type"]), ("Template", model["template"] or "custom"),
            ("IODB", f'{tb.get("iodb_file", "")} {("rev " + tb["iodb_revision"]) if tb.get("iodb_revision") else ""}'.strip()),
            ("I/O Assignment", f'{tb.get("io_file", "")} {("rev " + tb["io_revision"]) if tb.get("io_revision") else ""}'.strip()),
            ("Generated by", tb.get("generated_by", "")), ("Generated", tb.get("generated_at", ""))]
    for i, (k, v) in enumerate(info):
        ws.cell(3 + i, 1, k).font = F_BOLD
        ws.cell(3 + i, 3, v).font = F_BASE

    top = 3 + len(info) + 2
    pos: dict[str, tuple[int, int, int]] = {}            # id -> (top row, left col, right col, bottom row) via tuple pieces
    rects: dict[str, tuple[int, int, int, int]] = {}
    if vertical:
        for col, w in zip("ABCDEF", (3, 26, 8, 48, 4, 54)):
            ws.column_dimensions[col].width = w
        r = top
        for b in main:
            end = _write_block(ws, b, r, 4, 4)
            rects[b["id"]] = (r, 4, end, 4)
            r = end + 1 + 5                                   # 5 rows for the cable link
        for b in side:
            tgt = rects.get(b["attach_to"])
            start = tgt[0] if tgt else top
            end = _write_block(ws, b, start, 2, 2)
            rects[b["id"]] = (start, 2, end, 2)
        diagram_end = r
        for l in model["links"]:
            a, c = rects.get(l["from_id"]), rects.get(l["to_id"])
            if not a or not c:
                continue
            if a[1] == c[1] == 4:                              # main chain: vertical arrow + cable text
                y1, y2 = a[2] + 1, c[0] - 1
                for rr in range(y1, y2 + 1):
                    cell = ws.cell(rr, 4, "│" if rr < y2 else "▼")
                    cell.alignment, cell.font = CENTER, F_BASE
                text = [x["text"] for x in l["lines"]]
                if l["wires"]:
                    text.append(f'{len(l["wires"])} wires: ' + ", ".join(w["label"] for w in l["wires"]))
                sh = l["shield"]
                text.append("Shield: " + (sh["type"] or "NOT DEFINED") + (f" · {sh['termination']}" if sh["termination"] else ""))
                for k, t in enumerate(text[: y2 - y1 + 1 + 3]):
                    cell = ws.cell(y1 + k, 6, t)
                    cell.font = F_MISS if (k < len(l["lines"]) and l["lines"][k]["missing"]) or t.endswith("NOT DEFINED") else F_BASE
                    cell.alignment = LEFT_NW
            else:                                              # side component -> target
                ws.cell(a[0] + 1, 3, "──►").alignment = CENTER
                ws.cell(a[0] + 2, 3, f'{len(l["wires"])}w').font = F_SMALL
        table_col, table_row = 8, top
        for col, w in zip("GHIJKLMNOPQR", (3, 26, 26, 20, 16, 12, 22, 10, 10, 14, 14, 34)):
            ws.column_dimensions[col].width = w
        last_diagram_row = diagram_end
    else:
        ws.column_dimensions["A"].width = 3
        c = 2
        for b in main:
            ws.column_dimensions[get_column_letter(c)].width = 34
            ws.column_dimensions[get_column_letter(c + 1)].width = 24
            c += 2
        c = 2
        deepest = top
        for b in main:
            end = _write_block(ws, b, top, c, c)
            rects[b["id"]] = (top, c, end, c)
            deepest = max(deepest, end)
            c += 2
        for l in model["links"]:
            a, cc = rects.get(l["from_id"]), rects.get(l["to_id"])
            if not a or not cc or a[1] + 2 != cc[1]:
                continue
            gap_col = a[1] + 1
            ws.cell(top + 1, gap_col, "──────►").alignment = CENTER
            text = [x["text"] for x in l["lines"]] + [f'{len(l["wires"])} wires']
            sh = l["shield"]
            text.append("Shield: " + (sh["type"] or "NOT DEFINED"))
            for k, t in enumerate(text):
                cell = ws.cell(top + 2 + k, gap_col, t)
                cell.font, cell.alignment = F_BASE, LEFT_NW
        for k, b in enumerate(side):
            end = _write_block(ws, b, deepest + 2, 2, 2)
            deepest = max(deepest, end)
        table_col, table_row = 2, deepest + 3
        last_diagram_row = deepest

    # tables ------------------------------------------------------------------
    r = table_row
    wire_rows = []
    names = {b["id"]: (b["title"] or b["heading"]) for b in model["blocks"]}
    for l in model["links"]:
        cf = l.get("cable_fields", {})
        sh = l["shield"]
        shield = (sh["type"] or "NOT DEFINED") + (f" ({sh['termination']})" if sh["termination"] else "")
        for w in l["wires"]:
            wire_rows.append([names.get(l["from_id"], ""), names.get(l["to_id"], ""), cf.get("tag") or "—", cf.get("type") or "—",
                              cf.get("length") or "—", w["label"], w["colour"], w["number"], w["terminal_from"],
                              w["terminal_to"], shield])
    r = _table(ws, r, table_col, "WIRING SCHEDULE",
               ["From", "To", "Cable tag", "Cable type", "Length", "Wire", "Colour", "Wire no.", "Terminal from",
                "Terminal to", "Shield"], wire_rows)
    if model["signals"]:
        r = _table(ws, r, table_col, "SIGNALS IN THIS LOOP",
                   ["Signal", "Type", "Direction", "I/O type", "Rack", "Slot", "Module", "Channel", "Terminals / status"],
                   [[s["name"], s["type"], s["direction"].replace("_", " "), s["io_type"], s["rack"], s["slot"], s["module"],
                     s["channel"], (s["terminal"] + " · " if s["terminal"] else "") + s["status"]] for s in model["signals"]])
    _table(ws, r, table_col, "SOURCE DATA", ["Field", "Value", "Source"],
           [[x["label"], x["value"], x["source"]] for x in model["sources"]])

    for rr in range(2, ws.max_row + 1):                       # uniform rows: tables beside the diagram cannot stretch its blocks
        ws.row_dimensions[rr].height = 15
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = 8                                # A3
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
    from openpyxl.worksheet.properties import PageSetupProperties
    ws.sheet_properties.pageSetUpPr = PageSetupProperties(fitToPage=True)


def build_workbook(items: list[dict]) -> bytes:
    """items: [{"tag", "model"}]  ->  workbook bytes, one sheet per loop."""
    wb = Workbook()
    wb.remove(wb.active)
    used: set[str] = set()
    for item in items:
        ws = wb.create_sheet(safe_sheet_name(item["tag"], used))
        write_loop_sheet(ws, item["model"])
    if not wb.worksheets:
        raise ValueError("No loops to write.")
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
