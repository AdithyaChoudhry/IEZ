def norm_type(text: Any) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9/]+", " ", str(text or "").lower().replace("&", " and "))).strip()


def type_tokens(text: Any) -> set[str]:
    out: set[str] = set()
    for tok in norm_type(text).replace("/", " / ").split():
        if tok == "/":
            continue
        out.update(_ABBR.get(tok, [tok]))
    if "d" in out and "p" in out:                                 # "D P transmitter"
        out.update(["differential", "pressure"])
    return out


def match_type(text: Any) -> dict:
    """-> {template_id, status: exact|alias|keyword|ambiguous|unmatched, candidates, reason}. Never guesses."""
    n = norm_type(text)
    if not n:
        return {"template_id": None, "status": "unmatched", "candidates": [], "reason": "No instrument type."}
    lib = library()
    for t in lib:
        if n == norm_type(t["display_name"]):
            return {"template_id": t["id"], "status": "exact", "candidates": [t["id"]], "reason": "Same name as the template."}
    for t in lib:
        if any(n == norm_type(a) for a in t.get("aliases", [])):
            return {"template_id": t["id"], "status": "alias", "candidates": [t["id"]], "reason": "Known alias of the template."}
    toks = type_tokens(text)
    hits = []
    for t in lib:
        best = 0
        for rule in t.get("rules", []):
            if all(w in toks for w in rule["all"]) and not any(w in toks for w in rule.get("none", [])):
                best = max(best, len(rule["all"]))
        if best:
            hits.append((best, t["id"]))
    if len(hits) == 1:
        tid = hits[0][1]
        return {"template_id": tid, "status": "keyword", "candidates": [tid],
                "reason": "Matched by its key words - confirm the template."}
    if len(hits) > 1:
        hits.sort(reverse=True)
        if hits[0][0] > hits[1][0]:
            return {"template_id": hits[0][1], "status": "keyword", "candidates": [h[1] for h in hits],
                    "reason": "Matched by its key words (most specific of several) - confirm the template."}
        return {"template_id": None, "status": "ambiguous", "candidates": [h[1] for h in hits],
                "reason": "Fits more than one template - choose the right one."}
    cand = []
    try:
        from rapidfuzz import fuzz
        scored = sorted(((max(fuzz.token_set_ratio(n, norm_type(a)) for a in [t["display_name"], *t.get("aliases", [])]), t["id"])
                         for t in lib), reverse=True)
        cand = [tid for sc, tid in scored[:3] if sc >= 60]
    except Exception:                                             # pragma: no cover
        pass
    return {"template_id": None, "status": "unmatched", "candidates": cand,
            "reason": "No template in the library for this type" + (" - closest templates suggested." if cand else ".")}


# ── IODB analysis (all instrument rows - gauges, switches and orifices have no AI signal) ─────────────────────────
def _clean(v: Any) -> str:
    s = "" if v is None else str(v).strip()
    return "" if s.lower() in ("nan", "none") else re.sub(r"\s+", " ", s)


# ── instrument vs. non-instrument IODB entries ──────────────────────────────────────────────────────────────────
# The IODB lists every I/O point: motors (commands, feedbacks, speed), valves (open / close commands, status),
# DCS soft points (alarms, indications, fault flags) and the field instruments. Only field instruments get a
# datasheet, so only they are offered for selection.
_NOT_INSTRUMENT = {
    "motor", "motors", "pump", "blower", "agitator", "compressor", "conveyor", "chute", "loading", "button", "lamp",
    "electromagnet", "command", "cmd", "feedback", "status", "permissive", "start", "stop", "strat", "trip", "ready",
    "running", "run", "speed", "setpoint", "reference", "valve", "valves", "positioner", "postioner", "mov", "xv", "vfd",
    "mcc", "starter", "alarm", "alatm", "alarms", "fault", "indication", "indidation", "totaliser", "totalizer",
    "current", "profibus", "modbus", "local", "remote", "interlock", "heater", "fan", "damper", "actuator", "solenoid",
}
_INSTRUMENT = {
    "transmitter", "element", "switch", "swtich", "gauge", "indicator", "indicatoe", "rotameter", "rota", "analyzer",
    "analyser", "meter", "orifice", "flume", "sensor", "probe", "thermocouple", "rtd", "thermowell", "venturi",
    "detector", "glass", "radar", "ultrasonic", "manometer", "thermometer", "hygrometer", "density", "conductivity",
}


def is_instrument_type(text: Any) -> bool:
    """True for a field instrument type (transmitter, switch, gauge, element ...), False for motors, valves,
    commands / feedbacks and DCS soft points (alarms, indications, fault flags)."""
    toks = set(norm_type(text).replace("/", " ").split())
    expanded = type_tokens(text)
    if toks & _NOT_INSTRUMENT:
        return False
    if (toks | expanded) & _INSTRUMENT:
        return True
    m = match_type(text)
    return m["status"] in ("exact", "alias")


def analyze_iodb(iodb_bytes: bytes) -> dict:
    df, err = _load_iodb_df(iodb_bytes)
    if err or df is None:
        raise LibraryError(f"The IODB could not be read: {err}")
    cols = {"tag": _find_column(df, IODB_TAG_KEYS), "type": _find_column(df, IODB_TYPE_KEYS),
            "name": _find_column(df, IODB_NAME_KEYS), "description": _find_column(df, IODB_DESC_KEYS),
            "signal": _find_column(df, IODB_SIGNAL_KEYS), "subsystem": _find_column(df, IODB_SUBSYS_KEYS)}
    if not cols["tag"]:
        raise LibraryError("The IODB has no TAG NO column.")
    if not cols["type"] and not cols["name"] and not cols["description"]:
        raise LibraryError("The IODB has no INSTRUMENT TYPE, INSTRUMENT NAME or DESCRIPTION column.")
    groups: dict[str, dict] = {}
    hidden: dict[str, set] = {}
    for _, row in df.iterrows():
        tag = _clean(row.get(cols["tag"]))
        if not tag:
            continue
        typ = _clean(row.get(cols["type"])) if cols["type"] else ""
        desc = " ".join(x for x in (_clean(row.get(cols["name"])) if cols["name"] else "",
                                    _clean(row.get(cols["description"])) if cols["description"] else "") if x)
        key = typ or (f"(no type) {desc}" if desc else "")
        if not key:
            continue
        if not is_instrument_type(typ or desc):
            h = hidden.setdefault(typ or desc, set())
            h.add(tag)
            continue
        g = groups.setdefault(key, {"instrument_type": typ or desc, "type_blank": not typ, "tags": [], "seen": {},
                                    "descriptions": {}})
        g["seen"][tag] = g["seen"].get(tag, 0) + 1
        if g["seen"][tag] == 1:
            g["tags"].append(tag)
        if desc:
            g["descriptions"][desc] = g["descriptions"].get(desc, 0) + 1
    out = []
    names = {t["id"]: t["display_name"] for t in library()}
    for key, g in groups.items():
        m = match_type(g["instrument_type"])
        how = "type"
        if g["type_blank"]:
            how = "description"
            if m["template_id"]:
                m = {**m, "status": "description",
                     "reason": "No instrument type in the IODB; matched from the description - confirm the template."}
        elif not m["template_id"] and g["descriptions"]:
            top = max(g["descriptions"], key=g["descriptions"].get)
            md = match_type(top)
            if md["template_id"]:
                m = {**md, "status": "description",
                     "reason": f"Instrument type not recognised; matched from the description '{top}' - confirm the template."}
                how = "description"
        out.append({"instrument_type": g["instrument_type"], "tag_count": len(g["tags"]), "tags": sorted(g["tags"]),
                    "duplicates": sorted(t for t, n in g["seen"].items() if n > 1),
                    "template_id": m["template_id"], "template_name": names.get(m["template_id"]),
                    "status": m["status"], "candidates": [{"id": c, "name": names.get(c)} for c in m["candidates"]],
                    "reason": m["reason"], "matched_on": how,
                    "descriptions": sorted(g["descriptions"], key=g["descriptions"].get, reverse=True)[:3]})
    out.sort(key=lambda g: (g["template_id"] is None, g["instrument_type"].lower()))
    return {"columns": cols, "rows": int(len(df)), "groups": out,
            "supported": sum(1 for g in out if g["template_id"]), "unsupported": [g["instrument_type"] for g in out if not g["template_id"]],
            "hidden": sorted(({"instrument_type": k, "tag_count": len(v)} for k, v in hidden.items()),
                             key=lambda x: x["instrument_type"].lower()),
            "hidden_tags": sum(len(v) for v in hidden.values())}


# ── field rules from the Example / Engineering Guide ─────────────────────────────────────────────────────────────
_REF1 = re.compile(r"refer\s*annexure[\s\-_]*(i|1)\b(?![iv])", re.I)
_REF2 = re.compile(r"refer\s*annexure[\s\-_]*(ii|2)\b", re.I)


@dataclass
class LibField:
    spec: FieldSpec                 # the field as the existing engines see it (row, value_cols, defaults, ...)
    scope: str                      # tag | annexure2 | common
    origin: str                     # iodb | template | vendor | computed | optional | input
    note: str                       # Engineering Guide SOURCE note (section-propagated)
    example: list[str]              # the Engineering Guide value(s), shown as an example only for vendor fields
    unit: str = ""

    def to_dict(self) -> dict:
        s = self.spec
        return {"key": field_key(s), "section": s.section, "label": s.label, "row": s.row, "value_cols": s.value_cols,
                "sub_labels": s.sub_labels, "defaults": s.defaults, "input_type": s.input_type, "options": s.options,
                "mandatory": s.mandatory, "source": s.source, "color": s.color, "source_note": self.note,
                "scope": self.scope, "origin": self.origin, "example": self.example, "unit": self.unit}


def _unit(label: str) -> str:
    m = re.search(r"\(([^)]{1,16})\)\s*$", label)
    return m.group(1) if m else ""


@lru_cache(maxsize=1)
def _learned_tag_labels(mtime: float) -> frozenset:
    """Labels that are tag-wise ('REFER ANNEXURE-I') in the library's Engineering Guides - used for templates without one."""
    out = set()
    for t in library():
        try:
            r = roles_for(t)
            if r["example"]:
                eg = sheets_of(t)[r["example"]]
                for f in parse_field_spec(eg, eg):
                    if any(_REF1.search(d or "") for d in f.defaults):
                        out.add(re.sub(r"\s*\(.*?\)", "", f.label).strip().lower())
        except Exception:
            continue
    return frozenset(out)


# ── manual-entry dropdown options ───────────────────────────────────────────────────────────────────────────────
# Options come only from engineering sources: the template's own Engineering Guide value, the values the OTHER library
# templates' Engineering Guides use for the same field, and the generic datasheet_kb.json lists. The kb lists for
# "type", "sensor type", accuracy etc. are radar-specific, so they are offered only on radar templates.
_RADAR_ONLY_KB = {"type", "sensor type", "frequency range", "beam angle", "accuracy", "repeatability",
                  "temperature compensation", "mounting position", "process connection moc"}
_GENERIC_LABELS = {"type", "material", "size", "rating", "range", "model", "model no", "connection", "mounting", "service"}
_NOT_A_VALUE = re.compile(r"refer\s*annexure|^\s*[xX]+\s*$|^\s*-+\s*$|^\s*$")


def _opt_key(label: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"\(.*?\)", "", str(label or "")).lower().replace("&", " and ")).strip(" :.-")


@lru_cache(maxsize=4)
def _guide_values(mtime: float) -> dict[str, dict[str, list[str]]]:
    """{label key: {template id: [Engineering Guide values]}} across the library (common, non-vendor fields)."""
    out: dict[str, dict[str, list[str]]] = {}
    for t in library():
        try:
            lf, info = fields_for(t, _with_options=False)
        except Exception:                                         # pragma: no cover - a broken template is reported elsewhere
            continue
        if info.get("derived"):
            continue
        for f in lf:
            if f.scope != "common" or f.origin in ("vendor", "computed"):
                continue
            vals = [re.sub(r"\s+", " ", str(v)).strip() for v in f.example if not _NOT_A_VALUE.search(str(v or ""))]
            if vals:
                for k in {_opt_key(f.spec.label), f"{_opt_key(f.spec.section)}|{_opt_key(f.spec.label)}"}:
                    bucket = out.setdefault(k, {}).setdefault(t["id"], [])
                    bucket.extend(v for v in vals if v not in bucket)
    return out


def field_options(t: dict, f: "LibField") -> list[str]:
    from .sop_datasheet import load_kb as _load_kb, normalize as _kbnorm, CUSTOM_VALUE
    if f.scope != "common" or f.origin == "computed":
        return []
    key = _opt_key(f.spec.label)
    opts: list[str] = []

    def add(v):
        v = re.sub(r"\s+", " ", str(v or "")).strip()
        if v and not _NOT_A_VALUE.search(v) and v != CUSTOM_VALUE and v.lower() not in {o.lower() for o in opts}:
            opts.append(v)
    for v in f.spec.defaults:
        add(v)
    for v in f.example:
        add(v)
    if f.origin != "vendor":
        same_cat = {x["id"] for x in library() if x.get("category") == t.get("category")}
        if key in _GENERIC_LABELS:                                # "Type", "Material" ... mean different things per section
            gv = {i: v for i, v in _guide_values(_lib_path().stat().st_mtime).get(f"{_opt_key(f.spec.section)}|{key}", {}).items()
                  if i in same_cat}
        else:
            gv = _guide_values(_lib_path().stat().st_mtime).get(key, {})
        for tid in sorted(gv, key=lambda i: (i != t["id"], i not in same_cat, i)):
            for v in gv[tid]:
                add(v)
    try:
        kb = _load_kb()
    except Exception:                                             # pragma: no cover
        kb = {}
    kb_key = _kbnorm(f.spec.label)
    if kb_key in kb and (kb_key not in _RADAR_ONLY_KB or "radar" in t["id"]):
        for v in kb[kb_key]:
            add(v)
    return opts + [CUSTOM_VALUE] if opts else []


def fields_for(t: dict, field_scope: Optional[dict] = None, _with_options: bool = True) -> tuple[list[LibField], dict]:
    """Field rules of a template. `field_scope` ({key: tag|common}) corrects tag-wise/common for templates without a guide."""
    sheets = sheets_of(t)
    roles = roles_for(t)
    main = sheets[roles["main"]]
    eg = sheets.get(roles["example"]) if roles["example"] else None
    info = {"derived": eg is None, "notes": []}
    eg_rows: dict[int, int] = {}                                   # main row -> Engineering Guide row (for SOURCE notes)
    if eg is not None:
        # The guide and the main sheet usually share their row layout, but not always (an extra row in the guide shifts
        # everything below it). Fields are paired by section + label + occurrence, and the MAIN sheet's cells are used.
        def k(f):
            return (re.sub(r"\W", "", f.section.lower()), re.sub(r"\W", "", f.label.lower()))
        main_specs, seen = {}, {}
        for f in parse_field_spec(main, main):
            seen[k(f)] = seen.get(k(f), 0) + 1
            main_specs[(*k(f), seen[k(f)])] = f
        specs, seen, unmatched = [], {}, []
        for f in parse_field_spec(eg, eg):
            seen[k(f)] = seen.get(k(f), 0) + 1
            m = main_specs.get((*k(f), seen[k(f)]))
            if m is None:
                unmatched.append(f.label)
                continue
            eg_rows[m.row] = f.row
            specs.append(replace(f, row=m.row, value_cols=m.value_cols, sub_labels=m.sub_labels,
                                 defaults=(f.defaults + [""] * len(m.value_cols))[:len(m.value_cols)]))
        if unmatched:
            info["notes"].append(f"{len(unmatched)} Engineering Guide field(s) are not on the main datasheet and are left out: "
                                 f"{', '.join(unmatched[:5])}.")
    else:
        specs = parse_field_spec(main, main)
    # SOURCE notes apply from their row down to the next note or section change
    notes: dict[int, str] = {}
    if eg is not None:
        cur, cur_sec = "", None
        for f in specs:
            n = eg.value(eg_rows.get(f.row, f.row), 11).strip()
            if f.section != cur_sec:
                cur, cur_sec = "", f.section
            if n:
                cur = n
            notes[f.row] = cur if n or cur else ""
    learned = _learned_tag_labels(_lib_path().stat().st_mtime) if eg is None else frozenset()
    tag_secs = {s.upper() for s in t.get("tag_sections", [])}
    out: list[LibField] = []
    for f in specs:
        note = notes.get(f.row, "")
        nu = note.upper()
        example = list(f.defaults)
        if eg is not None:
            if any(_REF2.search(d or "") for d in f.defaults):
                scope = "annexure2"
            elif any(_REF1.search(d or "") for d in f.defaults) or f.source == "iodb":
                scope = "tag"
            else:
                scope = "common"
        else:
            base = re.sub(r"\s*\(.*?\)", "", f.label).strip().lower()
            scope = "tag" if (f.section.upper() in tag_secs or base in learned) else "common"
        scope = (field_scope or {}).get(field_key(f), scope) if eg is None else scope
        spec = f
        origin = "template"
        if scope == "tag":
            origin = "iodb"
            spec = replace(f, source="iodb", input_type="iodb", options=[], mandatory=False,
                           defaults=["REFER ANNEXURE-I"] * len(f.value_cols))
        elif scope == "annexure2":
            origin = "computed"
            spec = replace(f, source="iodb", input_type="iodb", options=[], mandatory=False,
                           defaults=["REFER ANNEXURE-II"] * len(f.value_cols))
        else:
            label_n = re.sub(r"\W+", " ", f.label.lower()).strip()
            if "VENDOR DETAILS" in nu and "SPECIFICATION" not in nu:
                origin = "vendor"
                spec = replace(f, source="predefined", defaults=[""] * len(f.value_cols), mandatory=False,
                               input_type="text" if f.input_type == "iodb" else f.input_type)
            elif "P&ID" in nu.replace(" ", "") and label_n in ("qty", "quantity"):
                origin = "computed"
                spec = replace(f, source="predefined", defaults=[""] * len(f.value_cols), mandatory=False, input_type="text")
            elif "TO BE REMOVED" in nu:
                origin = "optional"
            if eg is None:
                spec = replace(spec, source="predefined", mandatory=False,
                               input_type=spec.input_type if spec.input_type != "iodb" else "text")
                origin = "input" if not any(spec.defaults) else "template"
        out.append(LibField(spec, scope, origin, note, example, _unit(f.label)))
    if _with_options:
        for lf in out:
            opts = field_options(t, lf)
            lf.spec = replace(lf.spec, options=opts,
                              input_type="dropdown" if opts else ("iodb" if lf.scope != "common" else "text"))
    return out, info


# ── consolidated context ─────────────────────────────────────────────────────────────────────────────────────────
@dataclass
class LibContext:
    t: dict
    roles: dict
    lib_fields: list[LibField]
    ctx: SC.Context
    derived_annexure: bool
    notes: list[str] = field(default_factory=list)


def _derived_annexure(t: dict, main: SheetModel, lib_fields: list[LibField]) -> SC.AnnexureSpec:
    """An Annexure-I laid out from the datasheet's own tag-wise rows (only for templates that have none)."""
    cols = [SC.AnnexCol(0, "SL.No.", "", "SL.No.", "serial"), SC.AnnexCol(1, "TAG NO.", "", "TAG NO.", "tag")]
    c = 2
    for lf in lib_fields:
        if lf.scope != "tag" or re.sub(r"\W", "", lf.spec.label.lower()) == "tagno" and lf.spec.section.upper() == "GENERAL":
            continue
        head = lf.spec.label.upper() if lf.spec.section.upper() not in ("GENERAL", "PROCESS CONDITIONS") else lf.spec.label.upper()
        if lf.spec.section.upper() == "TANK DETAILS" and not head.startswith("TANK"):
            head = f"TANK {head}"
        if lf.spec.sub_labels:
            for sub in lf.spec.sub_labels:
                cols.append(SC.AnnexCol(c, head, sub.upper(), f"{head} · {sub.upper()}", "data"))
                c += 1
        else:
            cols.append(SC.AnnexCol(c, head, "", head, "data"))
            c += 1
    cols.append(SC.AnnexCol(c, "REMARKS", "", "REMARKS", "data"))
    return SC.AnnexureSpec("ANNEXURE-I", 6, 8, 9, cols, 1, 0)


def load_context(template_id: str, iodb_bytes: bytes, field_scope: Optional[dict] = None) -> LibContext:
    t = entry(template_id)
    roles = roles_for(t)
    sheets = sheets_of(t)
    lib_fields, info = fields_for(t, field_scope)
    df, err = _load_iodb_df(iodb_bytes)
    if err or df is None:
        raise LibraryError(f"The IODB could not be read: {err}")
    tag_col = _find_column(df, IODB_TAG_KEYS)
    if tag_col is None:
        raise LibraryError("The IODB has no TAG NO column.")
    derived = False
    if roles["annexure"]:
        ann = SC.parse_annexure(sheets[roles["annexure"]])
        if ann is None:
            raise LibraryError(f"The Annexure-I sheet of '{t['display_name']}' could not be read.")
    else:
        ann, derived = _derived_annexure(t, sheets[roles["main"]], lib_fields), True
    ctx = SC.Context(sheets, roles["main"], roles["main"], [lf.spec for lf in lib_fields], df, tag_col, ann, [])
    return LibContext(t, roles, lib_fields, ctx, derived, info["notes"])


# ── document header (CLIENT / PROJECT / doc numbers ...) placeholders ───────────────────────────────────────────────
HEADER_FIELDS = {"client": "Client", "consultant": "Consultant", "project": "Project", "plant": "Plant / Location",
                 "client_doc_no": "Client Doc. No.", "vatech_doc_no": "VA TECH WABAG Doc. No.", "rev": "Revision",
                 "prepared_by": "Prepared By", "date": "Date"}
_HEAD_LABEL = {"client": "client", "consultant": "consultant", "project": "project", "plant": "plant", "location": "plant",
               "client doc no": "client_doc_no", "client doc no.": "client_doc_no", "vatech doc no": "vatech_doc_no",
               "va tech doc no": "vatech_doc_no", "vatech doc no.": "vatech_doc_no", "rev": "rev", "rev no": "rev",
               "prepared by": "prepared_by", "date": "date"}
_PLACEHOLDER = re.compile(r"^\s*[xX]{1,}\s*$|^\s*SHEET\s+X\s+OF\s+Y\s*$")


def _hlabel(v: Any) -> Optional[str]:
    n = re.sub(r"[^a-z0-9 ]+", " ", str(v or "").lower()).strip()
    n = re.sub(r"\s+", " ", n)
    return _HEAD_LABEL.get(n)


def fill_header(ws, values: dict, first_field_row: Optional[int] = None) -> int:
    """Replace XXXXXX placeholders next to (or under) header labels. Returns how many placeholders remain."""
    from openpyxl.cell.cell import MergedCell
    remaining = 0
    mx_r, mx_c = min(ws.max_row, 120), min(ws.max_column, 40)
    for r in range(1, mx_r + 1):
        for c in range(1, mx_c + 1):
            cell = ws.cell(r, c)
            if isinstance(cell, MergedCell):
                continue
            v = cell.value
            empty_header = (v in (None, "") and first_field_row and r <= first_field_row and c <= 3)
            if not (isinstance(v, str) and _PLACEHOLDER.match(v)) and not empty_header:
                continue
            if isinstance(v, str) and v.strip().upper().startswith("SHEET"):
                continue
            key = None
            for cc in range(c - 1, 0, -1):                       # label to the left
                lv = ws.cell(r, cc).value
                if lv not in (None, "") and str(lv).strip() not in (":",):
                    key = _hlabel(str(lv).replace(":", " "))
                    break
            if key is None:
                for rr in (r - 1, r - 2):                         # label above (footer blocks)
                    if rr >= 1 and ws.cell(rr, c).value not in (None, ""):
                        key = _hlabel(str(ws.cell(rr, c).value).replace(":", " "))
                        break
            if key is None:
                continue
            val = str(values.get(key, "") or "").strip()
            if val:
                cell.value = val
            elif isinstance(v, str):
                remaining += 1
    return remaining


