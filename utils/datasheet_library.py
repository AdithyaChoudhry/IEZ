"""
datasheet_library.py - the Datasheet Generator's standard template library.

    backend/app/templates/datasheets/library.json   one entry per instrument: id, names, aliases, matching rules,
                                                     sheet roles (pinned, checked against detection)
    backend/app/templates/datasheets/<id>.xlsx       the workbook (converted once from the original .xls so logos,
                                                     merges, print areas and page setup are kept); never modified

What this module adds on top of the existing engines (sop_datasheet / sop_consolidated, reused, not changed):

  * sheet roles      main datasheet, Example / Engineering Guide, Annexure-I, Annexure-II (spare), checklist,
                     cover, index - from names AND content
  * field rules      read from the Example sheet: 'REFER ANNEXURE-I' = tag-wise (annexure), 'REFER ANNEXURE-II' =
                     spare sheet, a value = template default; the SOURCE column note decides vendor / P&ID / optional
                     fields. The OUTPUT is the clean main datasheet - the Example sheet is the guide, not the document.
  * type matching    IODB instrument type -> template: exact / alias / keyword rules with exclusions; anything
                     uncertain is reported, never silently assigned
  * consolidated     one workbook from a copy of the template: cover + index + main datasheet + Annexure-I (expanded
                     to the selected tags) + Annexure-II; Example and checklist sheets are left out of the document
  * no-annexure      a template without its own annexure (SOP LT) gets Annexure-I built from its tag-wise rows,
                     clearly reported as generated by iEZ
"""
