"""
Junction Box Schedule Generator (sub-generator of the Cable Schedule module).

  GET  /cable-schedule/jb/status     generated Cable Schedule, project name and design parameters
  POST /cable-schedule/jb/analyze    junction boxes, instrument / cable counts, terminals, missing inputs
  POST /cable-schedule/jb/validate   the engineer's confirmed values -> terminals used, spare, spare %, errors, warnings
  POST /cable-schedule/jb/generate   the one-sheet workbook (JB_SCHEDULE)
  GET  /cable-schedule/jb/download   the last generated workbook

The input is always the Cable Schedule last generated by the Cable Schedule Generator for this user and project (read here,
server side). The Junction Box Schedule is a standalone deliverable: it has no cover sheet and nothing here reads one. The
header of the JB_SCHEDULE sheet is filled from the project record and from what the engineer enters (never invented).
"""
import hashlib
import io
import logging
import threading
import re
from datetime import date
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from sqlalchemy.orm import Session

from ..auth.models import User
from ..deps import get_current_user, get_db
from ..models.document_registry import Project
from . import deliverables as _deliverables
from .cable_schedule import generated_meta, get_generated

import sys
sys.path.insert(0, '/app')
from utils import junction_box_schedule as jbs  # noqa: E402

router = APIRouter(prefix="/cable-schedule/jb", tags=["Junction Box Schedule"])
logger = logging.getLogger("iez.jb")

MODULE = "jb_schedule"            # key of the Excel / PDF download slot (/deliverables/jb_schedule/pdf); not a cover sheet
TEMPLATE_PATH = Path(__file__).resolve().parent.parent / "templates" / "junction_box_schedule" / "JB_SCHEDULE_TEMPLATE.xlsx"
NOT_GENERATED = "No generated Cable Schedule is available. Please generate the Cable Schedule first."
# header details of the JB_SCHEDULE sheet that the engineer may enter (all optional; a blank stays blank)
HEADER_FIELDS = {"project_description": "PROJECT", "client": "CLIENT", "pmc": "PMC / CONSULTANT", "contractor": "CONTRACTOR",
                 "document_number": "DOCUMENT NO.", "revision": "REVISION"}
HEADER_MAX = 200

_cache: dict = {}                # (user id, project, generated id) -> {"analysis": ..., "schedule_name": ...}; the user's latest only
_outputs: dict = {}              # (user id) -> {"bytes", "filename", "generated_id"}
_lock = threading.Lock()


class JBRequest(BaseModel):
    project_id: Optional[str] = None
    generated_id: Optional[str] = None
    jbs: dict = {}               # JB number -> the engineer's confirmed values
    design: Optional[dict] = None
    header: Optional[dict] = None    # optional header details (HEADER_FIELDS) typed by the engineer


def _bad(msg: str, code: int = status.HTTP_400_BAD_REQUEST):
    raise HTTPException(status_code=code, detail=msg)


def _schedule(user: User, project_id: Optional[str], generated_id: Optional[str]) -> dict:
    g = get_generated(user.id, project_id)
    if g is None:
        _bad(NOT_GENERATED, status.HTTP_404_NOT_FOUND)
    if generated_id and generated_id != g["id"]:
        _bad(f"A newer Cable Schedule ({g['filename']}, generated {g['generated_at']}) is now available. "
             "The page has been refreshed - analyze the junction boxes again.", status.HTTP_409_CONFLICT)
    return g


def _analysis(user: User, g: dict) -> dict:
    key = (user.id, (g.get("project_id") or ""), g["id"])
    with _lock:
        hit = _cache.get(key)
    if hit:
        return hit
    try:
        analysis = jbs.analyze(jbs.read_schedule(g["bytes"]), jbs.read_iodb_info(g.get("iodb_bytes")))
    except jbs.JBError as e:
        _bad(str(e))
    with _lock:
        for k in [k for k in _cache if k[0] == user.id]:         # keep only this user's latest analysis
            del _cache[k]
        _cache[key] = analysis
    return analysis


def _design(raw: Optional[dict]) -> dict:
    d = dict(jbs.DESIGN_DEFAULTS)
    for k, v in (raw or {}).items():
        if k in d:
            try:
                d[k] = float(v) if k == "design_spare_pct" else int(v)
            except (TypeError, ValueError):
                _bad(f"Design parameter {k} must be a number.")
    if d["design_spare_pct"] > 1:                                  # entered as a percentage
        d["design_spare_pct"] = d["design_spare_pct"] / 100.0
    return d


def _header(raw: Optional[dict]) -> dict:
    """The engineer's optional header details, cleaned. Unknown keys are dropped; nothing is invented or defaulted here."""
    out = {}
    for k in HEADER_FIELDS:
        v = re.sub(r"\s+", " ", str((raw or {}).get(k) or "")).strip()
        if len(v) > HEADER_MAX:
            _bad(f"{HEADER_FIELDS[k].title()} is longer than {HEADER_MAX} characters.")
        out[k] = v
    return out


def _project_name(db: Session, project_id: Optional[str]) -> str:
    """The registered name of the project (project management record, read-only); '' when there is none."""
    if not project_id:
        return ""
    row = db.query(Project).filter(Project.project_id == project_id).first()
    return (row.name or "").strip() if row else ""


def _public(an: dict) -> dict:
    return {k: an[k] for k in ("jbs", "instrument_total", "sheets", "notes")}


@router.get("/status")
async def jb_status(project_id: Optional[str] = None, user: User = Depends(get_current_user), db: Session = Depends(get_db)):
    g = get_generated(user.id, project_id)
    meta = generated_meta(g)
    if not meta["available"]:
        meta["message"] = NOT_GENERATED
    return {"generated": meta, "project_name": _project_name(db, project_id), "design": jbs.DESIGN_DEFAULTS,
            "lists": jbs.LISTS, "categories": jbs.CATEGORIES}


@router.post("/analyze")
async def jb_analyze(body: JBRequest, user: User = Depends(get_current_user), db: Session = Depends(get_db)):
    g = _schedule(user, body.project_id, body.generated_id)
    analysis = await run_in_threadpool(_analysis, user, g)
    design = _design(body.design)
    ev = jbs.evaluate_all(analysis, body.jbs or {}, design)
    return {"generated": generated_meta(g), "project_name": _project_name(db, body.project_id), "design": design,
            "lists": jbs.LISTS, "categories": jbs.CATEGORIES, "analysis": _public(analysis), "evaluation": ev}


@router.post("/validate")
async def jb_validate(body: JBRequest, user: User = Depends(get_current_user)):
    g = _schedule(user, body.project_id, body.generated_id)
    analysis = await run_in_threadpool(_analysis, user, g)
    return {"evaluation": jbs.evaluate_all(analysis, body.jbs or {}, _design(body.design))}


def _filename(doc_no: str, revision: str) -> str:
    """Junction_Box_Schedule.xlsx, or <document no.>_<revision>_Junction_Box_Schedule.xlsx when the engineer entered both."""
    if doc_no and revision:
        return re.sub(r"[^A-Za-z0-9._-]+", "_", f"{doc_no}_{revision}_Junction_Box_Schedule").strip("_") + ".xlsx"
    return "Junction_Box_Schedule.xlsx"


def _remember(user: User, data: bytes, filename: str) -> None:
    """Slot for the shared Excel / PDF download buttons (/deliverables/jb_schedule/*). No cover is resolved or added."""
    _deliverables._outputs[(user.id, MODULE)] = {
        "bytes": data, "filename": filename, "info": {"applied": False}, "pdf": None, "pdf_status": None, "pdf_error": None,
        "digest": hashlib.sha256(data).hexdigest()}


@router.post("/generate")
async def jb_generate(body: JBRequest, user: User = Depends(get_current_user)):
    g = _schedule(user, body.project_id, body.generated_id)
    analysis = await run_in_threadpool(_analysis, user, g)
    ev = jbs.evaluate_all(analysis, body.jbs or {}, _design(body.design))
    if ev["duplicates"]:
        _bad("A junction box appears more than once: " + ", ".join(ev["duplicates"]), status.HTTP_422_UNPROCESSABLE_ENTITY)
    blocked = [r for r in ev["results"] if r["status"] != "Ready"]
    if blocked:
        first = blocked[0]
        why = (first["errors"] or [f"Input required: {', '.join(first['missing_generation'])}"])[0]
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail={
            "message": f"{len(blocked)} junction box(es) need attention before the schedule can be generated. {first['jb_no']}: {why}",
            "evaluation": ev})
    if not TEMPLATE_PATH.exists():
        _bad("The standard Junction Box Schedule template is not installed on the server.", status.HTTP_500_INTERNAL_SERVER_ERROR)
    hdr = _header(body.header)
    meta = {"project_info": {k: hdr[k] for k in ("project_description", "client", "pmc", "contractor")},
            "document_number": hdr["document_number"], "revision": hdr["revision"], "date": date.today().strftime("%d.%m.%Y")}
    template = TEMPLATE_PATH.read_bytes()
    try:
        out = await run_in_threadpool(jbs.build_workbook, template, ev["results"], meta)
    except jbs.JBError as e:
        _bad(str(e))
    name = _filename(hdr["document_number"], hdr["revision"])
    import openpyxl
    names = openpyxl.load_workbook(io.BytesIO(out), read_only=True).sheetnames
    problems = jbs.formula_problems(out)
    if names != ["JB_SCHEDULE"] or problems:
        logger.error("JB schedule workbook failed its structure check: %s %s", names, problems[:5])
        _bad("The generated workbook failed its integrity check (" + ("; ".join(problems[:3]) or f"sheets {names}") + ").",
             status.HTTP_500_INTERNAL_SERVER_ERROR)
    _remember(user, out, name)
    with _lock:
        _outputs[user.id] = {"bytes": out, "filename": name, "generated_id": g["id"]}
    n_warn = sum(len(r["warnings"]) for r in ev["results"])
    return {"filename": name, "message": f"Junction Box Schedule generated: {len(ev['results'])} junction box(es).",
            "warnings": n_warn, "submission_ready": ev["submission_ready"],
            "missing_for_submission": {r["jb_no"]: r["missing_submission"] for r in ev["results"] if r["missing_submission"]},
            "evaluation": ev}


@router.get("/download")
async def jb_download(user: User = Depends(get_current_user)):
    out = _outputs.get(user.id)
    if not out:
        _bad("No Junction Box Schedule has been generated yet.", status.HTTP_404_NOT_FOUND)
    return StreamingResponse(io.BytesIO(out["bytes"]),
                             media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                             headers={"Content-Disposition": f'attachment; filename="{out["filename"]}"'})
